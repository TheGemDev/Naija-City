export interface InvestmentDef {
  id: string;
  title: string;
  location: string;
  /** 'world' is not a place: coins trade the same in every city. */
  city: 'kaduna' | 'abuja' | 'lagos' | 'kano' | 'world';
  icon: string;
  category: 'agric' | 'transport' | 'food' | 'energy' | 'property' | 'industry' | 'tech' | 'mining' | 'crypto';
  costPerUnit: number;
  description: string;
  tag: string;
  risk: 'Low' | 'Medium' | 'High';
  /** A real coin (its ticker). The price follows the real market instead of the game's own (worker/market.ts). */
  symbol?: string;
  /** Coins only: how much of the coin one unit is, the least you can buy. The coin itself costs its real dollar price times USD_NGN, and a unit that share of it. */
  lot?: number;
}

