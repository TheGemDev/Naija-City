export interface Holding {
  id: string;
  units: number;
  /** What the units still held cost to buy. Missing on holdings bought before this was tracked. */
  cost?: number;
  /** Profit or loss banked from units already sold. */
  realized?: number;
}

/** What a holding cost to buy. Older holdings have no record, so they count at the launch price. */
export const paidFor = (inv: InvestmentDef, h: Holding) => h.cost ?? h.units * inv.costPerUnit;

/** Share of the market price a player gets when liquidating a unit (the rest is the broker's spread). */
export const LIQUIDATION_FACTOR = 0.95;
/** Most units one buy or sale can carry (the server refuses more, worker/wallet.ts). */
export const MAX_TRADE_UNITS = 100;

/** The server (worker/market.ts) moves every venture's price on this beat. */
export const TICK_MS = 5 * 60_000;
/** Price swing per tick (standard deviation, as a fraction) by risk. */
export const VOLATILITY: Record<InvestmentDef['risk'], number> = { Low: 0.004, Medium: 0.009, High: 0.016 };
/** A price can never leave this band around its launch price. Real coins are not held to it. */
export const PRICE_BOUNDS = { min: 0.5, max: 2.2 };
/** A real coin whose price has not come in for this long cannot be traded: the price shown is old, and whoever knows the real one would win every time. */
export const REAL_PRICE_STALE_MS = 3 * TICK_MS;

/** Latest price multiple per venture, filled in from /api/market (src/net/market.ts). Offline or as a guest it stays 1. */
const priceMult: Record<string, number> = {};
export const setPriceMult = (id: string, mult: number) => { if (Number.isFinite(mult) && mult > 0) priceMult[id] = mult; };
export const priceOf = (inv: InvestmentDef) => Math.round(inv.costPerUnit * (priceMult[inv.id] ?? 1));
