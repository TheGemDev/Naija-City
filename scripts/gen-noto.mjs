const chars = JSON.parse(readFileSync('node_modules/@iconify-json/noto/chars.json', 'utf8'));
for (const e of [...feed, ...places, ...wizard, ...mall, ...reactions, ...hud, ...adopt, ...inec]) {
  const n = chars[[...e].map((c) => c.codePointAt(0).toString(16)).filter((h) => h !== 'fe0f').join('-')];
  if (n) map[e] ??= n; else console.error('no noto icon for', e);
}
const names = [...new Set(Object.values(map))];
const icons = {};
for (const n of names) {
  const a = set.aliases?.[n]; const src = a ? a.parent : n;
  if (!set.icons[src]) { console.error('missing', n); continue; }
  icons[n] = set.icons[src];
}
const out = `// generated by scripts/gen-noto.mjs — do not edit
export const NOTO = ${JSON.stringify({ prefix: 'noto', width: set.width ?? 128, height: set.height ?? 128, icons })} as const;
export const NOTO_MAP: Record<string, string> = ${JSON.stringify(map)};
`;
writeFileSync('src/ui/notoData.ts', out);
